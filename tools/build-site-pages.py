#!/usr/bin/env python3
"""Writes the platform pages of pocketnomad.us: docs/ios/, docs/android/ and docs/pwa/.

    python3 tools/build-site-pages.py

All three share one feature table (FEATURES below), so the comparison can't
drift between pages. Edit the table or the page text here, run the script, and
commit the generated index.html files. Standard library only.
"""

from html import escape
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
APK_URL = "https://github.com/dougray/pocket-nomad/releases/latest/download/pocket-nomad.apk"
