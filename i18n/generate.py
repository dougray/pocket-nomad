#!/usr/bin/env python3
"""Generates the iPhone .strings files and the Android Translations.kt from i18n/strings.json.

Edit i18n/strings.json (English text -> es / fr), then run:  python3 i18n/generate.py
The English text is the key, so a screen only needs its literal wrapped (iOS: Text("...") is automatic;
Android: tr("...")). Anything without a translation simply shows in English.
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "i18n" / "strings.json").read_text())

def norm(s): return s.replace('\\"', '"')

def esc_strings(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
def esc_kotlin(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")

for lang in ("es", "fr"):
    out = root / "App" / "Resources" / "Localization" / f"{lang}.lproj" / "Localizable.strings"
    lines = ["/* Generated by i18n/generate.py from i18n/strings.json. First-pass translations: they need review by a native speaker. */"]
    lines += [f'"{esc_strings(norm(k))}" = "{esc_strings(norm(v[lang]))}";' for k, v in data.items() if v.get(lang)]
    out.write_text("\n".join(lines) + "\n")

kt = ["// Generated by i18n/generate.py from i18n/strings.json. Do not edit by hand.",
      "// First-pass translations: they need review by a native speaker.",
      "", "package org.nomadpocket.i18n", "", "object GeneratedTranslations {"]
for lang in ("es", "fr"):
    kt.append(f"    val {lang}: Map<String, String> = mapOf(")
    kt += [f'        "{esc_kotlin(norm(k))}" to "{esc_kotlin(norm(v[lang]))}",' for k, v in data.items() if v.get(lang)]
    kt.append("    )")
kt.append("}")
out = root / "android" / "mesh" / "src" / "main" / "java" / "org" / "nomadpocket" / "i18n" / "GeneratedTranslations.kt"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(kt) + "\n")
print("wrote", len(data), "strings")
